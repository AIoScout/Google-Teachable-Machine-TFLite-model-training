#!/usr/bin/env python3
"""Build every sketch for real, for esp32p4, and prove the export traps work.

Every other check in this directory reasons about SOURCE.  This one answers the
questions a reviewer actually asks:

  1. does each sketch compile AND LINK for esp32p4?
  2. does each folder hold the export it claims?  (A legacy model_settings.h in
     TFLite_OCR/ would build a sketch whose 28x28 front-end is handed a 96x96
     tensor; a single-glyph export in TFLite_Sign/ would run one Invoke where
     the model expects three.  Each .ino refuses the others with #error — but
     "there is an #error in the file" is not the same claim as "the #error
     fires", so this actually builds each crossed pair and requires the build
     to FAIL.)
  3. what does each one cost in flash, measured, not estimated?

There are three sketches: TFLite/ (legacy 96x96), TFLite_OCR/ (single glyph)
and TFLite_Sign/ (3-character sign).  The crossed check is pairwise in both
directions, so it is 3 normal builds plus 6 rejection builds.

The camera library (ESP32_P4_IMX219) is not vendored here, so a small stub
supplies its symbols.  The stub is generated into a scratch tree, is never
committed, never shipped, and never executed — it exists purely so the link
closes.  Everything else is the real sketch, unconditionally.

    python3 tools/ino_build_check.py [--arduino-cli PATH] [--config PATH]
                                     [--no-guard] [--keep DIR]

Exit 0 only if all three sketches link and all six crossed builds are
rejected.  --no-guard skips the six extra builds (they triple the runtime).

CAVEAT, and it is a real one: upstream arduino-esp32 does not define
ARDUINO_ARCH_ESP32P4, so image_provider.cpp compiles its camera wrapper out
(TFLITE_P4_HAS_ARDUINO_CAM_LIB == 0) and the link is satisfied by the stub
instead of by the library.  This check therefore proves that the sketch
compiles, links, and wires its data flow correctly; it does NOT prove the
camera wrapper's own code compiles.  See TFLite_OCR/README.md §7.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]      # TFLite_OCR/
REPO = ROOT.parent
SKETCHES = {
    "TFLite": REPO / "TFLite",
    "TFLite_OCR": ROOT,
    "TFLite_Sign": REPO / "TFLite_Sign",
}

# The Arduino IDE bundles arduino-cli; there is usually no `arduino-cli` on PATH.
IDE_CLI = Path("/Applications/Arduino IDE.app/Contents/Resources/app/"
               "lib/backend/resources/arduino-cli")

# Which export each folder is supposed to hold:
# (TM_OCR_GLYPH_MODEL, TM_SIGN_OCR_MODEL).  A pre-macro legacy export defines
# neither; that is accepted only where `required` below is empty.
EXPECT = {
    "TFLite": (0, 0),
    "TFLite_OCR": (1, 0),
    "TFLite_Sign": (0, 1),
}
REQUIRED = {
    "TFLite": (),                    # pre-macro legacy exports are legal
    "TFLite_OCR": ("TM_OCR_GLYPH_MODEL",),
    "TFLite_Sign": ("TM_SIGN_OCR_MODEL",),
}
# Text the .ino's #error must contribute.  Matching the message, not just the
# exit status, keeps "failed because the guard fired" distinct from "failed
# for any other reason" (a link error would otherwise pass the check).
GUARD_MSG = {
    "TFLite": "TFLite is the legacy",
    "TFLite_OCR": "TFLite_OCR needs",
    "TFLite_Sign": "TFLite_Sign needs",
    # The "this export belongs elsewhere" half of each pair.
    "TFLite_OCR_OTHER": "This is the 3-character sign export",
    "TFLite_Sign_OTHER": "This is the single-glyph OCR export",
}


def _guard_fired(sketch_name: str, out: str) -> bool:
    """True when the crossed build failed BECAUSE this sketch's guard spoke."""
    if GUARD_MSG[sketch_name] in out:
        return True
    other = GUARD_MSG.get(f"{sketch_name}_OTHER")
    return bool(other and other in out)

# The camera library is absent on the verification machine, so image_provider.cpp
# compiles its wrapper out and the link wants the symbols the library provides.
STUB = """\
// GENERATED by tools/ino_build_check.py — link-only stand-in for
// ESP32_P4_IMX219.  Never shipped, never executed.
#include "image_provider.h"
static uint8_t s_dummy[96 * 96 * 3];
bool CameraBegin() { return true; }
bool ImageProviderEnsureCamera() { return true; }
bool CameraUpdate() { return true; }
const uint8_t* CameraGetRgb() { return s_dummy; }
size_t CameraGetRgbSize() { return sizeof(s_dummy); }
int CameraGetRgbWidth() { return 96; }
const char* CameraGetName() { return "STUB"; }
void CameraSendRgbToSerialWb(uint16_t, uint16_t) {}
const uint8_t* CameraGetRgbImgSized() { return s_dummy; }
const uint8_t* CameraGetGrayImgSized() { return s_dummy; }
void ImageProviderConfigureCamera(int, bool) {}
"""


def exports_of(folder: Path) -> dict[str, int | None]:
    """The two routing macros a sketch folder's export declares (None = absent)."""
    header = folder / "model_settings.h"
    text = header.read_text(errors="replace") if header.exists() else ""
    got: dict[str, int | None] = {}
    for name in ("TM_OCR_GLYPH_MODEL", "TM_SIGN_OCR_MODEL"):
        got[name] = None
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith(f"#define {name}"):
                try:
                    got[name] = int(stripped.split()[-1])
                except (IndexError, ValueError):
                    got[name] = None
    return got


def stage(dest: Path, sketch_src: Path, model_settings: Path | None) -> Path:
    """Copy a sketch folder into a scratch tree Arduino will accept."""
    dest.mkdir(parents=True, exist_ok=True)
    for f in sketch_src.iterdir():
        if f.is_file() and f.suffix in (".ino", ".c", ".h", ".cpp"):
            shutil.copyfile(f, dest / f.name)
    if model_settings is not None:
        # Crossed pair: overwrite this folder's export with the other one's.
        shutil.copyfile(model_settings, dest / "model_settings.h")
    (dest / "stub_camera.cpp").write_text(STUB)
    return dest


def build(cli: str, config: Path | None, sketch: Path, build_path: Path,
          partition: str) -> tuple[bool, str]:
    cmd = [cli]
    if config:
        cmd += ["--config-file", str(config)]
    cmd += ["compile",
            "--fqbn", f"esp32:esp32:esp32p4:PartitionScheme={partition}",
            "--build-path", str(build_path),
            str(sketch)]
    p = subprocess.run(cmd, capture_output=True, text=True)
    return p.returncode == 0, p.stdout + p.stderr


def totals(out: str) -> dict[str, str]:
    got = {}
    for key, pat in (("flash", r"Sketch uses (\d+) bytes \((\d+)%\)"),
                     ("ram", r"Global variables use (\d+) bytes \((\d+)%\)")):
        m = re.search(pat, out)
        if m:
            got[key] = f"{int(m.group(1)):,} B ({m.group(2)}%)"
    return got


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--arduino-cli", default=os.environ.get("ARDUINO_CLI") or str(IDE_CLI))
    ap.add_argument("--config", type=Path, default=None,
                    help="arduino-cli config (use an isolated one to avoid "
                         "touching your normal install)")
    ap.add_argument("--partition", default="app13M_data7M_32MB",
                    help="PartitionScheme for the LINK check.  Default is the "
                         "13 MB APP slot on purpose: it takes flash size out of "
                         "the measurement so a failure means the CODE is wrong. "
                         "The printed size tells you what the real one must be "
                         "(the legacy sketch needs ~3.7 MB, which no stock "
                         "16 MB scheme provides — huge_app's 3 MB is not enough).")
    ap.add_argument("--no-guard", action="store_true",
                    help="skip the two crossed-export builds")
    ap.add_argument("--keep", type=Path, default=None,
                    help="keep the staged trees + build output here (default: temp)")
    args = ap.parse_args()

    if not Path(args.arduino_cli).exists():
        sys.exit(f"arduino-cli not found: {args.arduino_cli} — pass --arduino-cli")

    root = args.keep or Path(tempfile.mkdtemp(prefix="ino_build_check_"))
    if root.exists():
        shutil.rmtree(root)     # a stale tree would be measured, not the source
    root.mkdir(parents=True)
    print(f"staging in {root}\n")

    rc = 0

    # ── 1. each sketch, as shipped ──────────────────────────────────────
    for name, folder in SKETCHES.items():
        got = exports_of(folder)
        print(f"════ {name} ════")
        for macro, want in zip(("TM_OCR_GLYPH_MODEL", "TM_SIGN_OCR_MODEL"),
                               EXPECT[name]):
            value = got[macro]
            # A pre-macro export defines nothing, which is legal for the
            # legacy sketch (it is what every model deployed before the OCR
            # and sign work looks like) and fatal for the other two.
            want_text = (f"{want}, or absent if the export predates the macro"
                         if macro not in REQUIRED[name] else str(want))
            print(f"  export           : {macro} = "
                  f"{'<not defined>' if value is None else value} "
                  f"(want {want_text})")
            if value is None:
                if macro in REQUIRED[name]:
                    print("  ^^ MISSING — this folder does not hold the export it needs")
                    rc = 1
            elif value != want:
                print("  ^^ MISMATCH — this folder holds the wrong sketch's export")
                rc = 1
        sketch = stage(root / name / name, folder, None)
        ok, out = build(args.arduino_cli, args.config, sketch, root / name / "build",
                        args.partition)
        print(f"  compiles + links : {'YES' if ok else 'NO'}")
        for k, v in totals(out).items():
            print(f"  {k:16s} : {v}")
        if not ok:
            rc = 1
            for l in [l for l in out.splitlines() if "error" in l.lower()][-8:]:
                print(f"  {l}")
            if "exceeds available space" in out:
                print("  (that is a PARTITION failure, not a code failure — this "
                      "sketch needs a bigger APP slot than " + args.partition + ")")
        print()

    # ── 2. every crossed pair must be REJECTED ──────────────────────────
    # "the file contains an #error" is not the claim; "the build fails because
    # of it" is.  Only a build settles that.  Pairwise in both directions:
    # three sketches, six swaps.
    if not args.no_guard:
        for name, folder in SKETCHES.items():
            for other_name, other_folder in SKETCHES.items():
                if other_name == name:
                    continue
                print(f"════ {name} with {other_name}'s export "
                      f"(must NOT build) ════")
                sketch = stage(root / f"crossed_{name}_from_{other_name}" / name,
                               folder, other_folder / "model_settings.h")
                ok, out = build(args.arduino_cli, args.config, sketch,
                                root / f"crossed_{name}_from_{other_name}" / "build",
                                args.partition)
                fired = _guard_fired(name, out)
                print(f"  rejected         : {'YES' if not ok else 'NO — IT BUILT'}")
                print(f"  guard message    : "
                      f"{'yes' if fired else 'no (failed for another reason!)'}")
                if ok or not fired:
                    rc = 1
                    if ok:
                        print("  ^^ the swap was accepted: the export guard is "
                              "not armed")
                    else:
                        for l in [l for l in out.splitlines()
                                  if "error" in l.lower()][-4:]:
                            print(f"  {l}")
                print()

    if rc == 0:
        print("RESULT: all three sketches compile and link for esp32p4, each holds "
              "its own export, and each rejects every other sketch's export.")
    else:
        print("RESULT: FAILED — see the notes above.")
    print(f"\n(staged tree: {root})")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
